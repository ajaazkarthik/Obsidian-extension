import * as vscode from 'vscode';
import * as os from 'os';
import * as path from 'path';

/**
 * Installs the brain-usage enforcement hook into the user-level Copilot
 * customization folders (`~/.copilot/hooks`, `~/.copilot/instructions`).
 *
 * Why the extension writes these files instead of shipping them declaratively:
 * VS Code has no `contributes.hooks` contribution point, so an extension cannot
 * declare hooks in `package.json`. Writing them at activation is the only way to
 * make enforcement travel with the extension to every workspace and machine.
 *
 * Every file this module owns carries MANAGED_MARKER. A file without the marker
 * is treated as user-authored and is never overwritten.
 */

export const MANAGED_MARKER = 'obsidian-brain-managed';

const HOOK_CONFIG_NAME = 'obsidian-brain.json';
const GUARD_SCRIPT_NAME = 'brain_guard.py';
const INSTRUCTION_NAME = 'brain-first-workflow.instructions.md';

const HOOK_EVENTS = ['SessionStart', 'PostToolUse', 'PreCompact', 'Stop'] as const;

export interface InstallReport {
    installed: boolean;
    reason?: string;
    hooksDir: string;
    written: string[];
    skipped: string[];
    removed: string[];
}

export interface InstallOptions {
    homeDir?: string;
    vaultPath?: string;
}

export function copilotHooksDir(homeDir: string): string {
    return path.join(homeDir, '.copilot', 'hooks');
}

export function copilotInstructionsDir(homeDir: string): string {
    return path.join(homeDir, '.copilot', 'instructions');
}

/** Insert the ownership marker directly after the shebang so Python still parses it. */
export function withMarker(source: string): string {
    const marker = `# ${MANAGED_MARKER} - generated by the Obsidian Brain extension. Edits are overwritten on update.`;
    const lines = source.split('\n');
    if (lines[0]?.startsWith('#!')) {
        return [lines[0], marker, ...lines.slice(1)].join('\n');
    }
    return [marker, ...lines].join('\n');
}

export function isManaged(content: string): boolean {
    return content.includes(MANAGED_MARKER);
}

/** Quote a path for a shell command line on the target platform. */
function quote(value: string, platform: NodeJS.Platform): string {
    return platform === 'win32' ? `"${value}"` : `'${value.replace(/'/g, `'\\''`)}'`;
}

export function buildHookConfig(scriptPath: string, vaultPath?: string): Record<string, unknown> {
    // `command` is the cross-platform fallback used on macOS/Linux, so it is
    // always POSIX-quoted; `windows` overrides it on Windows.
    const posix = quote(scriptPath, 'linux');
    const windows = quote(scriptPath, 'win32');
    const env = vaultPath ? { OBSIDIAN_BRAIN_VAULT: vaultPath } : undefined;

    const hooks: Record<string, unknown[]> = {};
    for (const event of HOOK_EVENTS) {
        hooks[event] = [
            {
                type: 'command',
                command: `python3 ${posix} --event ${event}`,
                windows: `python ${windows} --event ${event}`,
                ...(env ? { env } : {}),
                timeout: 10,
            },
        ];
    }

    return { $managedBy: MANAGED_MARKER, hooks };
}

async function readTextIfPresent(uri: vscode.Uri): Promise<string | undefined> {
    try {
        const bytes = await vscode.workspace.fs.readFile(uri);
        return Buffer.from(bytes).toString('utf8');
    } catch {
        return undefined;
    }
}

async function writeText(uri: vscode.Uri, content: string): Promise<void> {
    await vscode.workspace.fs.createDirectory(vscode.Uri.file(path.dirname(uri.fsPath)));
    await vscode.workspace.fs.writeFile(uri, Buffer.from(content, 'utf8'));
}

async function readAsset(context: vscode.ExtensionContext, name: string): Promise<string> {
    const uri = vscode.Uri.joinPath(context.extensionUri, 'assets', name);
    const bytes = await vscode.workspace.fs.readFile(uri);
    return Buffer.from(bytes).toString('utf8');
}

/**
 * True when the open workspace already wires a brain guard hook.
 *
 * VS Code collects hooks from every location and runs them all, so installing
 * the user-level hook config on top of an existing workspace one would fire the
 * guard twice per event. The workspace copy wins because it is versioned with
 * the repository and can be reviewed.
 */
async function workspaceAlreadyGuards(): Promise<boolean> {
    for (const folder of vscode.workspace.workspaceFolders ?? []) {
        const hooksDir = vscode.Uri.joinPath(folder.uri, '.github', 'hooks');
        let entries: [string, vscode.FileType][];
        try {
            entries = await vscode.workspace.fs.readDirectory(hooksDir);
        } catch {
            continue;
        }
        for (const [name, type] of entries) {
            if (type !== vscode.FileType.File || !name.endsWith('.json')) continue;
            const content = await readTextIfPresent(vscode.Uri.joinPath(hooksDir, name));
            if (content?.includes(GUARD_SCRIPT_NAME)) return true;
        }
    }
    return false;
}

/**
 * Write the guard script, hook config and instruction into the user-level
 * Copilot folders. Idempotent, non-destructive, and never throws: a failure
 * here must not block extension activation.
 */
export async function installAgentHooks(context: vscode.ExtensionContext, options: InstallOptions = {}): Promise<InstallReport> {
    const homeDir = options.homeDir ?? os.homedir();
    const hooksDir = copilotHooksDir(homeDir);
    const report: InstallReport = { installed: false, hooksDir, written: [], skipped: [], removed: [] };

    const enabled = vscode.workspace.getConfiguration('obsidianBrain').get<boolean>('installAgentHooks');
    if (enabled === false) {
        report.reason = 'disabled by obsidianBrain.installAgentHooks';
        return report;
    }

    if (!context.extensionUri?.fsPath) {
        report.reason = 'extension URI unavailable';
        return report;
    }

    try {
        const scriptPath = path.join(hooksDir, 'scripts', GUARD_SCRIPT_NAME);
        const scriptUri = vscode.Uri.file(scriptPath);
        const existingScript = await readTextIfPresent(scriptUri);
        if (existingScript !== undefined && !isManaged(existingScript)) {
            report.skipped.push(scriptPath);
        } else {
            const source = withMarker(await readAsset(context, GUARD_SCRIPT_NAME));
            if (existingScript !== source) {
                await writeText(scriptUri, source);
                report.written.push(scriptPath);
            }
        }

        const configPath = path.join(hooksDir, HOOK_CONFIG_NAME);
        const configUri = vscode.Uri.file(configPath);
        const existingConfig = await readTextIfPresent(configUri);
        if (existingConfig !== undefined && !isManaged(existingConfig)) {
            report.skipped.push(configPath);
        } else if (await workspaceAlreadyGuards()) {
            // The workspace ships its own guard; a second config would double-fire.
            // Remove a config we wrote earlier, or it would keep firing alongside it.
            if (existingConfig !== undefined) {
                await vscode.workspace.fs.delete(configUri);
                report.removed.push(configPath);
            } else {
                report.skipped.push(configPath);
            }
        } else {
            const config = JSON.stringify(buildHookConfig(scriptPath, options.vaultPath), null, 2) + '\n';
            if (existingConfig !== config) {
                await writeText(configUri, config);
                report.written.push(configPath);
            }
        }

        const instructionPath = path.join(copilotInstructionsDir(homeDir), INSTRUCTION_NAME);
        const instructionUri = vscode.Uri.file(instructionPath);
        const existingInstruction = await readTextIfPresent(instructionUri);
        if (existingInstruction !== undefined && !isManaged(existingInstruction)) {
            report.skipped.push(instructionPath);
        } else {
            const asset = await readAsset(context, INSTRUCTION_NAME);
            const content = asset.includes(MANAGED_MARKER) ? asset : `${asset.trimEnd()}\n\n<!-- ${MANAGED_MARKER} -->\n`;
            if (existingInstruction !== content) {
                await writeText(instructionUri, content);
                report.written.push(instructionPath);
            }
        }

        report.installed = true;
        return report;
    } catch (error) {
        report.reason = error instanceof Error ? error.message : String(error);
        return report;
    }
}
